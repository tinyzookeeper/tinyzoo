import { buildRegistry, type CmsEntity, type Junction, propOf } from './entity'
import { camel, serializeColumn, snake } from './fields'
import { CMS_MEDIA_SOURCE } from './media'
import { CMS_SYSTEM_SOURCE } from './system'

/** Emit the on-disk db/schema.ts source from the entity descriptors. */
export function emitSchema(config: Record<string, any>): string {
  const reg = buildRegistry(config)
  const usesRich = reg.entities.some((e) => Object.values(e.fields).some((fl) => fl.type === 'richtext'))

  const out: string[] = []
  out.push('// GENERATED by @my-cms/core — DO NOT EDIT.')
  out.push('// Source: cms.config.ts. Regenerate with `pnpm db:generate`.')
  out.push(`import { pgTable, pgEnum, uuid, text, integer, numeric, boolean, timestamp, jsonb, primaryKey, index, uniqueIndex } from 'drizzle-orm/pg-core'`)
  if (usesRich) out.push(`import type { RichTextDoc } from '@my-cms/core'`)
  out.push('')

  // enums (hoisted — referenced by tables below)
  for (const e of reg.entities) {
    for (const en of e.enums) {
      out.push(`export const ${en.varName} = pgEnum('${en.enumName}', ${JSON.stringify([...en.values])})`)
    }
  }
  out.push('')

  // built-in media table
  out.push(CMS_MEDIA_SOURCE, '')

  // users, one-time links, audit log
  out.push(CMS_SYSTEM_SOURCE, '')

  // entity tables
  for (const e of reg.entities) out.push(emitEntityTable(e), '')

  // m2m junctions
  for (const j of reg.junctions) out.push(emitJunction(j), '')

  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n'
}

function emitEntityTable(e: CmsEntity): string {
  const lines: string[] = [`  id: uuid('id').primaryKey().defaultRandom(),`]
  for (const [key, fld] of Object.entries(e.fields)) {
    if (!fld.spec) continue
    const dbName = snake(key) + (fld.spec.nameSuffix ?? '')
    const enumVar = fld.spec.base.kind === 'enum' ? e.enums.find((en) => en.key === key)!.varName : undefined
    const refTargetVar = fld.spec.reference
      ? (fld.spec.reference.target === 'media' ? 'cmsMedia' : camel(fld.relation!.to().name))
      : undefined
    lines.push(`  ${propOf(key, fld)}: ${serializeColumn(fld.spec, dbName, { enumVar, refTargetVar })},`)
  }
  lines.push(`  createdAt: timestamp('created_at', { withTimezone: true, mode: 'date', precision: 3 }).notNull().defaultNow(),`)
  lines.push(`  updatedAt: timestamp('updated_at', { withTimezone: true, mode: 'date', precision: 3 }).notNull().defaultNow(),`)
  lines.push(`  createdBy: uuid('created_by'),`)
  lines.push(`  updatedBy: uuid('updated_by'),`)
  return `export const ${camel(e.name)} = pgTable('${e.name}', {\n${lines.join('\n')}\n})`
}

function emitJunction(j: Junction): string {
  return `export const ${camel(j.name)} = pgTable('${j.name}', {
  ${j.ownerCol}: uuid('${snake(j.ownerEntity)}_id').notNull().references(() => ${camel(j.ownerEntity)}.id, { onDelete: 'cascade' }),
  ${j.targetCol}: uuid('${snake(j.targetEntity)}_id').notNull().references(() => ${camel(j.targetEntity)}.id, { onDelete: 'cascade' }),
}, (t) => [primaryKey({ columns: [t.${j.ownerCol}, t.${j.targetCol}] })])`
}
