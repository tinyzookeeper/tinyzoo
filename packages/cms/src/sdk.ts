import { buildContentModel, type ContentField, type ContentFieldType, type EmbeddedShape, type RefShape } from './content-shape'

// Emit a self-contained, strictly-typed TypeScript client binding for the public
// content API, generated from cms.config.ts. The output declares one interface per
// public collection (mirroring the projected response shapes) plus a `ContentSchema`
// map and a pre-bound `createClient()` over the @tinyzoo/client runtime.
//
// A separate frontend (any framework) drops this one file in, `npm i @tinyzoo/client`,
// and gets fully-typed `cms.<collection>.list()/.get()` with zero schema coupling.

/** @internal */
export interface SdkOptions {
  /** Import specifier for the runtime client. Default '@tinyzoo/client'. */
  clientModule?: string
  /** Banner comment. */
  banner?: string
}

function pascalRef(name: string): string {
  return name.replace(/(^|[_-])([a-z0-9])/g, (_, __, c) => c.toUpperCase())
}

/** TypeScript type expression for a projected field value (without nullability). */
function tsType(t: ContentFieldType): string {
  switch (t.kind) {
    case 'scalar':
      if (t.enumValues) return t.enumValues.map((v) => `'${v}'`).join(' | ')
      if (t.scalar === 'integer' || t.scalar === 'number') return 'number'
      if (t.scalar === 'boolean') return 'boolean'
      return 'string' // string + datetime(ISO) both serialize as string
    case 'richtext': return 'RichTextDoc'
    case 'media': return 'CmsMedia'
    case 'gallery': return 'CmsGalleryItem[]'
    case 'relation-one': return t.public ? `${pascalRef(t.target)}Embedded` : `${pascalRef(t.target)}Ref`
    case 'relation-many': return `${t.public ? `${pascalRef(t.target)}Embedded` : `${pascalRef(t.target)}Ref`}[]`
    case 'blocks': {
      const variants = t.blocks.map((b) => {
        const fields = b.fields.map((f) => `${f.key}: ${tsType(f.type)}${f.nullable ? ' | null' : ''}`)
        return `{ id: string; type: '${b.type}'${fields.length ? `; ${fields.join('; ')}` : ''} }`
      })
      return `Array<${variants.length ? variants.join(' | ') : 'never'}>`
    }
    case 'group': {
      const fields = t.fields.map((f) => `${f.key}: ${tsType(f.type)}${f.nullable ? ' | null' : ''}`)
      return `{ ${fields.join('; ')} }`
    }
  }
}

function fieldLine(f: ContentField): string {
  const value = f.type.kind === 'relation-many'
    ? (f.nullable ? `(${tsType(f.type)}) | null` : tsType(f.type))
    : `${tsType(f.type)}${f.nullable ? ' | null' : ''}`
  return `  ${f.key}: ${value}`
}

function objectInterface(name: string, fields: ContentField[], opts: { timestamps: boolean; locales?: string[] | null; paths?: boolean; tree?: boolean }): string {
  const lines = ['  id: string', ...fields.map(fieldLine)]
  if (opts.timestamps) lines.push('  createdAt: string', '  updatedAt: string')
  if (opts.locales) {
    const union = opts.locales.map((l) => `'${l}'`).join(' | ')
    lines.push(`  /** The language this item is served in. */\n  locale: ${union}`, `  /** Languages this item exists in (the default and every translation). */\n  locales: Array<${union}>`)
    if (opts.paths) lines.push(`  /** The item's address in each language it exists in. */\n  paths: Partial<Record<${union}, string>>`)
  }
  if (opts.tree) {
    lines.push(
      "  /** The page's address in the language served: its ancestors' address parts and its own, language prefix included. */\n  path: string | null",
      '  /** From the top of the tree down to this page (itself last): title and address of each. */\n  breadcrumbs: Array<{ title: string; path: string }>',
    )
  }
  return `export interface ${name} {\n${lines.join('\n')}\n}`
}

function embeddedInterface(e: EmbeddedShape): string {
  return objectInterface(`${e.pascal}Embedded`, e.fields, { timestamps: false })
}

function refInterface(r: RefShape): string {
  const titleLine = `  ${r.titleField}: ${tsType(r.titleType)}${r.titleNullable ? ' | null' : ''}`
  return `export interface ${r.pascal}Ref {\n  id: string\n${titleLine}\n}`
}

/** @internal */
export function emitContentTypes(config: Record<string, any>, opts: SdkOptions = {}): string {
  const model = buildContentModel(config)
  const clientModule = opts.clientModule ?? '@tinyzoo/client'

  const out: string[] = []
  out.push(opts.banner ?? '// GENERATED by tinyzoo — DO NOT EDIT.')
  out.push('// Typed client for the public content API. Regenerate with `tinyzoo client`.')
  out.push(`import { createCmsClient, type ClientOptions, type CmsClient } from '${clientModule}'`)
  out.push('')

  // Shared primitives.
  out.push('/** A ProseMirror/TipTap rich-text document. Render structurally — never as raw HTML. */')
  out.push('export interface RichTextNode {')
  out.push('  type: string')
  out.push('  text?: string')
  out.push('  content?: RichTextNode[]')
  out.push('  marks?: { type: string, attrs?: Record<string, unknown> }[]')
  out.push('  attrs?: Record<string, unknown>')
  out.push('  [k: string]: unknown')
  out.push('}')
  out.push('export interface RichTextDoc {')
  out.push("  type: 'doc'")
  out.push('  content?: RichTextNode[]')
  out.push('}')
  out.push('')
  out.push('/** A populated media field. */')
  out.push('export interface CmsMedia {')
  out.push('  id: string')
  out.push('  url: string')
  out.push('  width: number | null')
  out.push('  height: number | null')
  out.push('  alt: string | null')
  out.push('  mime: string')
  out.push('  /** Focal point in percent (0–100) of width and height: keep it in view when cropping. */')
  out.push('  focal: { x: number; y: number } | null')
  out.push('}')
  out.push('')
  out.push('/** One item of a gallery field: the file, and its caption. */')
  out.push('export interface CmsGalleryItem extends CmsMedia {')
  out.push('  caption: string | null')
  out.push('}')
  out.push('')

  // Embedded + ref shapes (nested populated targets).
  if (model.embedded.length || model.refs.length) {
    out.push('// ── nested (populated) projections ─────────────────────────────────────────────')
    for (const e of model.embedded) out.push(embeddedInterface(e))
    for (const r of model.refs) out.push(refInterface(r))
    out.push('')
  }

  // Top-level collection items.
  out.push('// ── collection items ────────────────────────────────────────────────────────────')
  for (const e of model.entities) out.push(objectInterface(e.pascal, e.fields, { timestamps: true, locales: e.locales, paths: e.paths, tree: e.tree }))
  out.push('')

  // Globals (singletons).
  if (model.globals.length) {
    out.push('// ── globals ─────────────────────────────────────────────────────────────────────')
    for (const g of model.globals) out.push(objectInterface(g.pascal, g.fields, { timestamps: true, locales: g.locales }))
    out.push('')
  }

  // Per-collection filter types.
  out.push('// ── query types ─────────────────────────────────────────────────────────────────')
  for (const e of model.entities) {
    const filterLines = e.filters.map((f) => {
      const t = f.value === 'boolean' ? 'boolean' : f.value === 'datetime' ? 'string | Date' : f.enumValues ? f.enumValues.map((v) => `'${v}'`).join(' | ') : 'string'
      const key = /^[A-Za-z_$][\w$]*$/.test(f.key) ? f.key : `'${f.key}'`
      const doc = f.value === 'datetime' ? `  /** ${f.key.endsWith('.from') ? 'On or after' : 'On or before'} this date or time. */\n` : ''
      return `${doc}  ${key}?: ${t}`
    })
    out.push(`export interface ${e.pascal}Filters {${filterLines.length ? `\n${filterLines.join('\n')}\n` : ''}}`)
  }
  out.push('')

  // The schema map consumed by the runtime client. A `type` alias (not `interface`)
  // so it satisfies the runtime's `Record<string, CollectionSpec>` constraint.
  out.push('/** Maps each collection to its item / sort keys / filters. */')
  out.push('export type ContentSchema = {')
  for (const e of model.entities) {
    const sort = e.sortKeys.map((k) => `'${k}'`).join(' | ')
    out.push(`  ${e.name}: { item: ${e.pascal}, sort: ${sort}, filters: ${e.pascal}Filters${e.tree ? ', tree: true' : ''} }`)
  }
  out.push('}')
  out.push('')

  out.push('/** Maps each global to its object (`cms.global(name)`). */')
  out.push(`export type GlobalSchema = {${model.globals.length ? `\n${model.globals.map((g) => `  ${g.name}: ${g.pascal}`).join('\n')}\n` : ''}}`)
  out.push('')

  // Pre-bound, fully-typed client factory.
  out.push('/** Create a typed client for this CMS. `baseUrl` is the CMS origin. */')
  out.push('export function createClient(options: ClientOptions): CmsClient<ContentSchema, GlobalSchema> {')
  out.push('  return createCmsClient<ContentSchema, GlobalSchema>(options)')
  out.push('}')
  out.push('')

  return out.join('\n').replace(/\n{3,}/g, '\n\n')
}
